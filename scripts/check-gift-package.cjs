const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { buildSync } = require('esbuild');
const { unzipSync, strFromU8 } = require('fflate');
const output = path.resolve('.room-qa/gift-package/package.cjs');
buildSync({ entryPoints: ['src/gift/publish/package.ts'], outfile: output, bundle: true, platform: 'node', format: 'cjs' });
const { buildGiftPackage, validateGiftPackage } = require(output);
const text = '</script><script>window.injected=true</script> & <img onerror=alert(1)>';
const payload = { version: 1, gift: { ...structuredClone(require('../src/world/demo-gift.json')), room: require('../src/room/default-room.json'), details: { recipient: '小河', sender: '小林', memory: text, extra_photos: [] } }, audio: null };
payload.gift.object_contents['sealed-letter'] = { kind: 'letter', body: text };
const runtime = fs.readFileSync('public/gift-viewer/runtime.js', 'utf8');
const notices = fs.readFileSync('public/gift-viewer/notices.txt', 'utf8');
const before = structuredClone(payload);
const archive = unzipSync(buildGiftPackage(payload, runtime, notices));
assert.deepEqual(payload, before, 'Packaging must never mutate the saved room or contents');
assert.deepEqual(Object.keys(archive).sort(), ['README.txt', 'THIRD_PARTY_NOTICES.txt', 'index.html', 'viewer.js']);
const html = strFromU8(archive['index.html']);
const embedded = html.match(/<script id="gift-data" type="application\/json">(.*?)<\/script>/s)[1];
assert.ok(!embedded.includes('<'), 'User text cannot break out of the data script');
assert.deepEqual(JSON.parse(embedded), payload);
assert.ok(!html.includes('https://') && html.includes('src="./viewer.js"'), 'The viewer has no remote scripts or absolute asset paths');
const bad = structuredClone(payload); bad.gift.object_contents['sunset-frame'].photo = 'https://example.com/private.jpg';
assert.throws(() => validateGiftPackage(bad), /照片或信件/);
assert.throws(() => validateGiftPackage({ ...payload, audio: { name: 'bad', type: 'text/html', base64: 'AAAA' } }), /音乐无效/);
const absent = structuredClone(payload); delete absent.gift.room;
assert.throws(() => validateGiftPackage(absent));
assert.throws(() => buildGiftPackage(payload, '', notices), /预览程序/);
console.log('PASS: self-contained ZIP, immutable snapshot, JSON/script injection escaping, relative assets, invalid media/room/runtime rejection');
